-- Sub-categories lookup table
--
-- Reference list of client/beneficiary sub-categories for the GIS form.
-- Follows the existing lookup-table convention (prefixed id + a single
-- descriptive column, e.g. gender_identities.gender_id / gender_identity).
--
-- Safe to re-run: the table is created only if missing and the seed uses
-- INSERT IGNORE against the unique sub_category name.

CREATE TABLE IF NOT EXISTS `sub_categories` (
  `subcat_id` INT NOT NULL AUTO_INCREMENT,
  `sub_category` VARCHAR(150) NOT NULL,
  PRIMARY KEY (`subcat_id`),
  UNIQUE KEY `uq_sub_category` (`sub_category`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

